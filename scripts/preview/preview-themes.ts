export const previewThemeOverrides = (theme: string | null): string => {
  if (!theme || !Object.hasOwn(WORKSPACE_PREVIEW_THEMES, theme)) return "";
  const values =
    WORKSPACE_PREVIEW_THEMES[theme as keyof typeof WORKSPACE_PREVIEW_THEMES];
  return `:root {\n${Object.entries(values)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n")}\n}`;
};
